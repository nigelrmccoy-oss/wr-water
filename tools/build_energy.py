#!/usr/bin/env python3
"""Build data/energy.js from IESO public reports saved in data/raw/ieso/ (v0.2).
Sources (all public, downloaded 2026-10-08/09):
  Ontario hourly demand 2026  https://reports-public.ieso.ca/public/Demand/PUB_Demand_2026.csv
  Day-ahead Ontario Zonal Price  https://reports-public.ieso.ca/public/DAHourlyOntarioZonalPrice/PUB_DAHourlyOntarioZonalPrice_YYYYMMDD.xml
  Global Adjustment (Class B rate + total $)  https://reports-public.ieso.ca/public/GlobalAdjustment/PUB_GlobalAdjustment_YYYYMM.xml
  ICI peak tracker 2026-27 base period  https://reports-public.ieso.ca/public/ICIPeakTracker/PUB_ICIPeakTracker_2026.xml
"""
import csv, json, re, glob, os
R = os.path.join(os.path.dirname(__file__), '..', 'data', 'raw', 'ieso')
rows = [r for r in csv.reader(open(os.path.join(R, 'PUB_Demand_2026.csv'))) if r and r[0][:1].isdigit()]
dem = {}
for r in rows:
    if '2026-05-01' <= r[0] <= '2026-08-31':
        dem.setdefault(r[0], [0] * 24)[int(r[1]) - 1] = int(r[3])
oz = {}
for f in sorted(glob.glob(os.path.join(R, 'ozp', '*.xml'))):
    t = open(f).read(); d = re.search(r'<DeliveryDate>([\d-]+)<', t)
    p = [float(x) for x in re.findall(r'<ZonalPrice>([-\d.]+)<', t)]
    if d and len(p) == 24: oz[d.group(1)] = p
ga = {}
for f in sorted(glob.glob(os.path.join(R, 'ga_2*.xml'))):
    t = open(f).read(); m = os.path.basename(f)[3:9]
    a = re.search(r'<Actual>([-\d.]+)<', t); s = re.search(r'<SecondEstimate>([-\d.]+)<', t)
    r1 = re.search(r'<ActualRate>([-\d.]+)<', t); r2 = re.search(r'<SecondEstimateRate>([-\d.]+)<', t)
    if not (a or s): continue
    ga[m[:4] + '-' + m[4:]] = {'totalDollars': float((a or s).group(1)), 'classBRatePerMWh': float((r1 or r2).group(1)), 'status': 'actual' if a else 'second estimate'}
t = open(os.path.join(R, 'ici2026.xml')).read()
pts = re.findall(r'<deliveryDate>([\d-]+)</deliveryDate>\s*<deliveryHour>(\d+)</deliveryHour>\s*</datetimeInfo>\s*<value>([\d.]+)</value>\s*<status>(\w+)</status>', t)
tracker = [{'date': d, 'he': int(h), 'mw': round(float(v), 1), 'status': s} for d, h, v, s in pts][:10]
out = {'ontarioDemandMW': dem, 'ozpDA': oz, 'ga': ga, 'iciTracker2026': tracker}
js = '// GENERATED by tools/build_energy.py from IESO public reports (data/raw/ieso). Do not edit by hand.\nexport const IESO = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open(os.path.join(os.path.dirname(__file__), '..', 'data', 'ieso.js'), 'w').write(js)
print('days demand', len(dem), 'ozp days', len(oz), 'GA months', len(ga), 'tracker', len(tracker))
